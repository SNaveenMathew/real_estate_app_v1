#!/usr/bin/env python3
"""Generate the reference tables that used to be maintained by hand.

Why
---
The audit found documented facts that had drifted from the code: a stale crime
row count and token cap in the README, a capability matrix referenced but never
written (``eval/CAPABILITY_MATRIX.md``), and endpoint tables that grow a new
route without anyone noticing. Each of those is a table whose source of truth is
already in the repository — the FastAPI app, ``config.Settings``, the approved
function registry in ``agents/capabilities.py``, and the eval set itself.

This script renders them:

    docs/REFERENCE.md          endpoints, approved functions, settings
    eval/CAPABILITY_MATRIX.md  catalog tables x fixture rows x golden examples

Usage
    python scripts/gen_docs_tables.py --write     # rewrite both files
    python scripts/gen_docs_tables.py --check     # exit 1 when they are stale

``--check`` is in CI, so a new route, a renamed setting or an eval example that
covers a new table shows up as a failing check instead of a stale document.

The matrix is measured, not asserted: the fixture is built into a temporary
database, each agent-visible table's row count is read from it, and each golden
example's *plan* (the deterministic planner, no model call) is inspected for the
tables it needs. A table with rows but no examples is therefore visible as a gap
rather than hidden behind prose.
"""
from __future__ import annotations

import argparse
import ast
import inspect
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

REFERENCE = ROOT / "docs" / "REFERENCE.md"
MATRIX = ROOT / "eval" / "CAPABILITY_MATRIX.md"

_HEADER = (
    "<!-- Generated by scripts/gen_docs_tables.py — do not edit by hand. -->\n"
    "<!-- Run `python scripts/gen_docs_tables.py --write` after a code change; CI runs --check. -->\n"
)


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(cell).replace("|", "\\|") for cell in row) + " |")
    return "\n".join(out)


def _walk_routes(routes):
    """Every APIRoute in the app, including the ones this FastAPI version keeps inside an ``_IncludedRouter``.

    ``app.routes`` is not a flat list any more: an included router stays a wrapper whose ``original_router`` holds
    the routes. Walking it recursively is stable across both shapes (a plain ``app.include_router`` result and the
    lazy wrapper), and it is what the audit's AST pass counted as 53 handlers.
    """
    from fastapi.routing import APIRoute

    for route in routes:
        if isinstance(route, APIRoute):
            yield route
        elif type(route).__name__ == "_IncludedRouter":
            original = getattr(route, "original_router", None)
            if original is not None:
                yield from _walk_routes(original.routes)
        elif hasattr(route, "routes"):
            yield from _walk_routes(route.routes)


def endpoint_rows() -> list[list[str]]:
    import main

    rows = []
    for route in _walk_routes(main.app.routes):
        summary = (inspect.getdoc(route.endpoint) or "").strip().splitlines()
        rows.append([
            ", ".join(sorted(route.methods)),
            f"`{route.path}`",
            summary[0] if summary else "",
            "async" if inspect.iscoroutinefunction(route.endpoint) else "sync",
        ])
    rows.sort(key=lambda r: (r[1], r[0]))
    return rows


def capability_rows() -> list[list[str]]:
    from agents.capabilities import describe

    return [[f"`{row['name']}`", row["tags"], row["deadline"], row["description"]] for row in describe()]


def config_rows() -> list[list[str]]:
    """Settings from ``config.py``: name, default and the trailing comment that documents it."""
    source = (ROOT / "config.py").read_text(encoding="utf-8")
    lines = source.splitlines()
    tree = ast.parse(source)
    rows: list[list[str]] = []
    for node in tree.body:
        if not (isinstance(node, ast.ClassDef) and node.name == "Settings"):
            continue
        for stmt in node.body:
            if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
                continue
            name = stmt.target.id
            default = ast.unparse(stmt.value) if stmt.value is not None else "—"
            comment = ""
            line = lines[stmt.lineno - 1] if stmt.lineno - 1 < len(lines) else ""
            if "#" in line:
                comment = line.split("#", 1)[1].strip()
            rows.append([f"`{name}`", f"`{default}`", comment])
    return rows


def matrix_rows() -> list[list[str]]:
    """Agent-visible tables: fixture rows and how many golden examples plan against them."""
    from eval.fixtures import build_fixture
    from eval.golden_set import GOLDEN_SET
    from agents.query_planner import build_query_plan
    import db.duckdb_store as store
    from db import schema_catalog as schema

    with tempfile.TemporaryDirectory() as tmp:
        build_fixture(Path(tmp) / "capability_fixture.duckdb")
        tables = sorted(schema.list_table_names(agent_visible_only=True))
        counts = {t: schema._row_count(t) for t in tables}
        store.close()

    coverage = {t: 0 for t in tables}
    for example in GOLDEN_SET:
        try:
            plan = build_query_plan(example.question)
        except Exception:
            continue
        for table in set(getattr(plan, "required_tables", []) or []) & set(tables):
            coverage[table] += 1

    rows = []
    for table in tables:
        examples = coverage[table]
        if counts[table] and not examples:
            status = "rows, no examples"
        elif counts[table]:
            status = "covered"
        elif examples:
            status = "examples, no fixture rows"
        else:
            status = "empty"
        rows.append([f"`{table}`", str(counts[table]), str(examples), status])
    return rows


def render_reference() -> str:
    parts = [
        _HEADER,
        "# Reference (generated)",
        "",
        "These tables are rendered from the code. The hand-written sections of `README.md` explain *why*; these",
        "are the facts — add a route, a setting or an approved function and re-run the generator.",
        "",
        "## HTTP endpoints",
        "",
        f"{len(endpoint_rows())} routes, from `main.app`.",
        "",
        _table(["Method", "Path", "Summary (first docstring line)", "Handler"], endpoint_rows()),
        "",
        "## Approved functions the agents may call",
        "",
        "The vocabulary a generated program can use (`agents/general_agent.py`), with what each may touch and the",
        "deadline it runs under (`agents/capabilities.py`).",
        "",
        _table(["Function", "Tags", "Deadline", "What it does"], capability_rows()),
        "",
        "## Settings",
        "",
        "Every field of `config.Settings` with its default and the comment that documents it.",
        "",
        _table(["Setting", "Default", "Documented as"], config_rows()),
        "",
    ]
    return "\n".join(parts)


def render_matrix() -> str:
    rows = matrix_rows()
    covered = sum(1 for r in rows if r[3] == "covered")
    parts = [
        _HEADER,
        "# Capability matrix",
        "",
        "What the evaluation set can certify, measured rather than claimed: for every agent-visible catalog table,",
        "the rows the deterministic fixture loads and the number of golden examples whose plan needs that table.",
        "",
        "A table with **rows but no examples** is a quality gate that does not exist yet; a table with **examples",
        "but no fixture rows** is an example that cannot pass until the fixture grows. `python scripts/gen_docs_tables.py",
        "--write` refreshes this file, and CI fails when it is stale.",
        "",
        _table(["Table", "Fixture rows", "Golden examples", "Status"], rows),
        "",
        f"**{covered} of {len(rows)} agent-visible tables are covered by at least one example.**",
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="rewrite the generated documents")
    group.add_argument("--check", action="store_true", help="exit 1 when a document is stale")
    args = parser.parse_args()

    targets = {REFERENCE: render_reference(), MATRIX: render_matrix()}
    if args.write:
        for path, content in targets.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
        return 0

    stale = []
    for path, content in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != content:
            stale.append(path.relative_to(ROOT))
    if stale:
        for path in stale:
            print(f"stale: {path}")
        print("Run `python scripts/gen_docs_tables.py --write` and commit the result.")
        return 1
    print("generated docs are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
